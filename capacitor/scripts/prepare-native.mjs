#!/usr/bin/env node
// Generates and patches the Capacitor native projects (capacitor/android, capacitor/ios).
//
// They are generated, not committed, the same way Expo's /android and /ios are: app.json is the source
// of truth, so `npm run rename` and an icon change reach both shells without hand-editing native files.
// Every patch is idempotent and fails loudly if the Capacitor template stops matching.
//
// Patches ported from swap (ivan-i1/swap@b71c719, web/android + web/ios):
//   Android — immersive full screen (MainActivity), release signing from ../credentials/keystore.properties,
//             version from app.json, orientation from app.json.
//   iOS     — bundle id from app.json (the Android package form is not a legal iOS id), version,
//             hidden status bar, orientation, export-compliance answer.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const cap = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(cap, '..');
const expo = JSON.parse(readFileSync(join(root, 'app.json'), 'utf8')).expo;
const appId = expo.android.package;
const iosBundleId = expo.ios?.bundleIdentifier ?? appId.replace(/_/g, '-');
const version = expo.version ?? '1.0.0';
const versionCode = expo.android?.versionCode ?? 1;
const buildNumber = expo.ios?.buildNumber ?? String(versionCode);
const orientation = expo.orientation ?? 'default';
const withIos = process.platform === 'darwin';

const run = (cmd, args) => execFileSync(cmd, args, { cwd: cap, stdio: 'inherit' });
const read = (p) => readFileSync(join(cap, p), 'utf8');
const write = (p, s) => writeFileSync(join(cap, p), s);
function patch(file, what, transform) {
  const before = read(file);
  const after = transform(before);
  if (after === null) throw new Error(`[prepare-native] ${what}: pattern not found in ${file}. Capacitor's template changed — update this script.`);
  if (after !== before) write(file, after);
}

// 0. capacitor.config.json is generated from app.json (gitignored), so a rename reaches it too.
//    appId uses the Android package; the iOS bundle id is patched in step 5, because the Android
//    form (underscores) is not a legal iOS bundle id.
write('capacitor.config.json', JSON.stringify({
  appId,
  appName: expo.name,
  webDir: 'dist',
  backgroundColor: '#0F1016',
  android: { allowMixedContent: false }, // everything is bundled; nothing is loaded from the network
  ios: { contentInset: 'never', scrollEnabled: false },
}, null, 2) + '\n');

if (!existsSync(join(cap, 'dist', 'index.html'))) {
  console.error('[prepare-native] dist/ is missing — run `npm run build` first.');
  process.exit(1);
}

// 1. Generate the native projects once.
if (!existsSync(join(cap, 'android'))) run('npx', ['cap', 'add', 'android']);
if (withIos && !existsSync(join(cap, 'ios'))) run('npx', ['cap', 'add', 'ios']);

// 2. Icons and splash from the same artwork the Expo app uses (assets/source/), in "logo" mode.
const logoSrc = existsSync(join(root, 'assets/source/foreground.png'))
  ? join(root, 'assets/source/foreground.png')
  : join(root, 'assets/source/icon.png');
mkdirSync(join(cap, 'resources'), { recursive: true });
copyFileSync(logoSrc, join(cap, 'resources', 'logo.png'));
const iconBg = expo.android?.adaptiveIcon?.backgroundColor ?? '#FFFFFF';
run('npx', [
  'capacitor-assets', 'generate', '--android', ...(withIos ? ['--ios'] : []), '--assetPath', 'resources',
  '--iconBackgroundColor', iconBg, '--iconBackgroundColorDark', iconBg,
  '--splashBackgroundColor', '#F7F7FA', '--splashBackgroundColorDark', '#0F1016',
]);

// 3. Copy the web build and plugin wiring into both projects.
run('npx', ['cap', 'sync']);

// 4. Android patches.
const javaDir = join('android/app/src/main/java', ...appId.split('.'));
write(join(javaDir, 'MainActivity.java'), `package ${appId};

import android.os.Bundle;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;
import com.getcapacitor.BridgeActivity;

// GENERATED by capacitor/scripts/prepare-native.mjs — edit the script, not this file.
public class MainActivity extends BridgeActivity {

    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        hideSystemBars();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        // The bars come back after dialogs and app switches; hide them again whenever the game is in front.
        if (hasFocus) hideSystemBars();
    }

    // Immersive full screen: status and navigation bars hidden; a swipe from the edge shows them briefly.
    private void hideSystemBars() {
        WindowCompat.setDecorFitsSystemWindows(getWindow(), false);
        WindowInsetsControllerCompat controller = WindowCompat.getInsetsController(getWindow(), getWindow().getDecorView());
        controller.hide(WindowInsetsCompat.Type.systemBars());
        controller.setSystemBarsBehavior(WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
    }
}
`);

patch('android/app/build.gradle', 'release signing', (g) => {
  if (g.includes('credentials/keystore.properties')) return g;
  const plugin = "apply plugin: 'com.android.application'";
  const release = /( {8}release \{\n)( {12}minifyEnabled)/;
  if (!g.includes(plugin) || !release.test(g) || !g.includes('    buildTypes {')) return null;
  return g
    .replace(plugin, `${plugin}

// Release signing from the repo-root credentials/keystore.properties (gitignored) — the same file the
// Expo build uses. storeFile in it is relative to the repo root. Without it, release builds are unsigned.
def keystorePropertiesFile = rootProject.file('../../credentials/keystore.properties')
def keystoreProperties = new Properties()
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.withInputStream { keystoreProperties.load(it) }
}`)
    .replace('    buildTypes {', `    signingConfigs {
        release {
            if (keystorePropertiesFile.exists()) {
                storeFile rootProject.file('../../' + keystoreProperties['storeFile'])
                storePassword keystoreProperties['storePassword']
                keyAlias keystoreProperties['keyAlias']
                keyPassword keystoreProperties['keyPassword']
            }
        }
    }
    buildTypes {`)
    .replace(release, `$1            if (keystorePropertiesFile.exists()) {
                signingConfig signingConfigs.release
            }
$2`);
});

patch('android/app/build.gradle', 'version', (g) => {
  if (!/versionCode \d+/.test(g) || !/versionName "[^"]*"/.test(g)) return null;
  return g.replace(/versionCode \d+/, `versionCode ${versionCode}`).replace(/versionName "[^"]*"/, `versionName "${version}"`);
});

const androidOrientation = { portrait: 'portrait', landscape: 'sensorLandscape' }[orientation];
if (androidOrientation) {
  patch('android/app/src/main/AndroidManifest.xml', 'orientation', (m) => {
    if (m.includes('android:screenOrientation=')) return m.replace(/android:screenOrientation="[^"]*"/, `android:screenOrientation="${androidOrientation}"`);
    if (!m.includes('android:name=".MainActivity"')) return null;
    return m.replace('android:name=".MainActivity"', `android:name=".MainActivity"\n            android:screenOrientation="${androidOrientation}"`);
  });
}

// 5. iOS patches.
if (withIos) {
  const pbx = 'ios/App/App.xcodeproj/project.pbxproj';
  patch(pbx, 'bundle id and version', (p) => {
    if (!p.includes('PRODUCT_BUNDLE_IDENTIFIER')) return null;
    return p
      .replace(/PRODUCT_BUNDLE_IDENTIFIER = [^;]+;/g, `PRODUCT_BUNDLE_IDENTIFIER = ${iosBundleId};`)
      .replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${version};`)
      .replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${buildNumber};`);
  });

  const iosOrientations = {
    portrait: ['UIInterfaceOrientationPortrait'],
    landscape: ['UIInterfaceOrientationLandscapeLeft', 'UIInterfaceOrientationLandscapeRight'],
  }[orientation];
  patch('ios/App/App/Info.plist', 'status bar, orientation, encryption', (plist) => {
    const end = plist.lastIndexOf('</dict>');
    if (end < 0) return null;
    let out = plist;
    const setBool = (key, value) => {
      const re = new RegExp(`<key>${key}</key>\\s*<(true|false)/>`);
      if (re.test(out)) out = out.replace(re, `<key>${key}</key>\n\t<${value}/>`);
      else {
        const at = out.lastIndexOf('</dict>');
        out = `${out.slice(0, at)}\t<key>${key}</key>\n\t<${value}/>\n${out.slice(at)}`;
      }
    };
    setBool('UIStatusBarHidden', true);
    setBool('UIViewControllerBasedStatusBarAppearance', false);
    setBool('ITSAppUsesNonExemptEncryption', false);
    if (iosOrientations) {
      const items = iosOrientations.map((o) => `\t\t<string>${o}</string>`).join('\n');
      out = out.replace(
        /(<key>UISupportedInterfaceOrientations(?:~ipad)?<\/key>\s*<array>)[\s\S]*?(<\/array>)/g,
        `$1\n${items}\n\t$2`
      );
    }
    return out;
  });
}

console.log(`[prepare-native] ${appId} (iOS ${iosBundleId}) v${version} (${versionCode}) — android${withIos ? ' + ios' : ''} ready.`);
