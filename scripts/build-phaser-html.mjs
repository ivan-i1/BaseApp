#!/usr/bin/env node
// Builds the self-contained page the native PhaserView loads: Phaser + the game's
// scenes bundled into one inline <script>, emitted as a TS module exporting the HTML
// string (src/engines/phaser/generated/phaserHtml.ts, gitignored). Runs on postinstall;
// re-run (`npm run phaser:build`) after editing anything under src/engines/phaser/.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/engines/phaser/generated/phaserHtml.ts');

const result = await build({
  entryPoints: [join(root, 'src/engines/phaser/webview-entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  // Android System WebView is evergreen Chromium; RN 0.81 requires iOS 15.1+ (WKWebView ES2020).
  target: 'es2020',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
});
// Inline <script> must not contain a literal closing tag.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body,#game{margin:0;padding:0;width:100%;height:100%;overflow:hidden;background:transparent;touch-action:none;-webkit-user-select:none;user-select:none}</style>
</head><body><div id="game"></div><script>${js}</script></body></html>`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// GENERATED by scripts/build-phaser-html.mjs — do not edit.\nconst html: string = ${JSON.stringify(html)};\nexport default html;\n`);
console.log(`[phaser:build] ${(html.length / 1024).toFixed(0)} KB → ${out.replace(root + '/', '')}`);
